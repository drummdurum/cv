const { test, expect } = require('@playwright/test');
const { randomUUID, createHmac } = require('crypto');
const { execFileSync } = require('child_process');

test('admin sender manglende invitationer, ser levering og sender aflysninger uden dubletter', async ({ page, request, baseURL }) => {
  test.skip(process.env.CALENDAR_LIFECYCLE_TEST !== 'true', 'Kræver isolerede Docker-containere og Mailpit.');
  test.setTimeout(60000);
  const container = process.env.TEST_CALENDAR_APP_CONTAINER;
  if (container !== 'cv-calendar-app-check-app-1') throw new Error('Testdata må kun oprettes i den isolerede testcontainer.');
  const key = process.env.TEST_CALENDAR_ADMIN_KEY;
  const mailpit = 'http://127.0.0.1:28025';
  const mailApi = 'http://127.0.0.1:23101';
  const apiHeaders = { 'x-api-key': 'local-development-key-cv-0000000000000' };
  const people = [0, 1].map(index => ({ id: randomUUID(), name: `Mangler invitation ${index}`, email: `missing-${randomUUID()}@example.test` }));
  const script = `const {MongoClient}=require('mongodb'); (async()=>{const c=new MongoClient(process.env.MONGODB_URI);await c.connect();const db=c.db(process.env.MONGODB_DB);const p=${JSON.stringify(people)};const old=await db.collection('participants').find({name:{$in:p.map(x=>x.name)}}).toArray();await db.collection('enrollments').deleteMany({participantId:{$in:old.map(x=>x.id)}});await db.collection('participants').deleteMany({id:{$in:old.map(x=>x.id)}});await db.collection('eventCancellations').deleteOne({_id:'gloegg-og-hygge'});await db.collection('participants').insertMany(p);await db.collection('enrollments').insertMany(p.map(x=>({eventId:'gloegg-og-hygge',participantId:x.id,createdAt:new Date()})));await c.close();})().catch(e=>{console.error(e.message);process.exit(1)});`;
  execFileSync('docker', ['exec', container, 'node', '-e', script]);
  const messagesFor = async email => {
    const body = await (await request.get(`${mailpit}/api/v1/messages`)).json();
    return body.messages.filter(message => message.To.some(to => to.Address === email));
  };
  const checkPanel = () => page.locator('details').filter({ has: page.locator('input[value="gloegg-og-hygge"]') }).filter({ has: page.getByRole('button', { name: 'Tjek kalenderinvitationer', exact: true, includeHidden: true }) });
  const check = async operation => {
    await page.goto('/event');
    const panel = checkPanel();
    await panel.locator('summary').click();
    await panel.getByLabel('Adminnøgle').fill(key);
    await panel.getByRole('button', { name: operation, exact: true }).click();
  };
  await check('Send manglende invitationer');
  await expect(page.locator('.invitation-report')).toContainText('2 manglende invitationer');
  for (const person of people) await expect.poll(async () => (await messagesFor(person.email)).length).toBe(1);
  await check('Send manglende invitationer');
  await expect(page.locator('.invitation-report')).toContainText('0 manglende invitationer');
  const uid = `gloegg-og-hygge-${people[0].id}@sebastiandrumm.dk`;
  const state = await (await request.get(`${mailApi}/emails/calendar/${encodeURIComponent(uid)}`, { headers: apiHeaders })).json();
  const log = await (await request.get(`${mailApi}/emails/${state.jobId}`, { headers: apiHeaders })).json();
  const event = JSON.stringify({ type: 'email.delivered', created_at: new Date().toISOString(), data: { email_id: log.mail.providerMessageId } });
  const timestamp = String(Math.floor(Date.now() / 1000));
  const id = `msg_${randomUUID()}`;
  const secret = Buffer.from('calendar-webhook-test-secret-00000');
  const signature = createHmac('sha256', secret).update(`${id}.${timestamp}.${event}`).digest('base64');
  const signed = await request.post(`${mailApi}/webhooks/resend`, { headers: { 'content-type': 'application/json', 'svix-id': id, 'svix-timestamp': timestamp, 'svix-signature': `v1,${signature}` }, data: event });
  expect(signed.status()).toBe(204);
  const forged = await request.post(`${mailApi}/webhooks/resend`, { headers: { 'content-type': 'application/json' }, data: event });
  expect(forged.status()).toBe(401);
  await check('Tjek kalenderinvitationer');
  await expect(page.locator('.invitation-report')).toContainText('Leveret til mailserver');
  const remove = page.locator('details').filter({ has: page.locator('input[value="gloegg-og-hygge"]') }).filter({ has: page.getByRole('button', { name: 'Fjern tilmelding', exact: true, includeHidden: true }) });
  await remove.locator('summary').click();
  await remove.getByLabel('Gæstens mail').fill(people[0].email);
  await remove.getByLabel('Adminnøgle').fill(key);
  await remove.getByRole('button', { name: 'Fjern tilmelding' }).click();
  await expect.poll(async () => (await messagesFor(people[0].email)).length).toBe(2);
  const cancelMail = (await messagesFor(people[0].email)).find(message => message.Subject.startsWith('Aflyst:'));
  const detail = await (await request.get(`${mailpit}/api/v1/message/${cancelMail.ID}`)).json();
  const calendar = await (await request.get(`${mailpit}/api/v1/message/${cancelMail.ID}/part/${detail.Attachments[0].PartID}`)).text();
  expect(calendar).toContain('METHOD:CANCEL');
  expect(calendar).toContain(`UID:${uid}`);
  expect(calendar).toContain('SEQUENCE:1');
  const cancelEvent = page.locator('details').filter({ has: page.locator('input[value="gloegg-og-hygge"]') }).filter({ has: page.getByRole('button', { name: 'Aflys event og send kalenderaflysninger', includeHidden: true }) });
  await cancelEvent.locator('summary').click();
  await cancelEvent.getByLabel('Adminnøgle').fill(key);
  await cancelEvent.getByRole('button').click();
  await expect(page.locator('.invitation-report')).toContainText('Eventet er aflyst');
  await expect.poll(async () => (await messagesFor(people[1].email)).length).toBe(2);
  await expect(page.locator('a.event-card').first()).toContainText('AFLYST');
  const csrf = await (await request.get('/event/api/csrf')).json();
  const rejected = await request.post('/event/api/participant', { headers: { origin: new URL(baseURL).origin, 'x-csrf-token': csrf.csrfToken }, data: { eventId: 'gloegg-og-hygge', name: 'For sent', email: 'late@example.test' } });
  expect(rejected.status()).toBe(409);
  expect((await messagesFor(people[0].email)).length).toBe(2);
});
